import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("rust")
}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// 发布签名（keystore.properties 在 .gitignore 里，密钥本体在仓库外的
// H:\develop\keystore\）：无该文件时 release 回退 debug 签名，开发机缺配置也能出包。
val keystoreProperties = Properties().apply {
    val propFile = file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    compileSdk = 36
    namespace = "com.quicknote.app"
    defaultConfig {
        // 0.38.4 用户反馈「自部署服务器怎么还会下载失败」：release 此前 false——
        // 应用内更新的 Kotlin 下载（HttpURLConnection）打自部署 http:// 端点会被
        // 明文策略当场拦死（同步走 Rust 原生栈不受此策略管，所以同步一直正常）。
        // 应用经 GitHub 分发不受商店政策约束，WebView 也不加载远程 http 内容，
        // 放开明文（debug 块原本就是 true）。
        manifestPlaceholders["usesCleartextTraffic"] = "true"
        applicationId = "com.quicknote.app"
        minSdk = 24
        targetSdk = 36
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            isMinifyEnabled = true
            proguardFiles(
                *fileTree(".") { include("**/*.pro") }
                    .plus(getDefaultProguardFile("proguard-android-optimize.txt"))
                    .toList().toTypedArray()
            )
            signingConfig = if (keystoreProperties.containsKey("storeFile")) {
                signingConfigs.create("release") {
                    storeFile = file(keystoreProperties.getProperty("storeFile"))
                    storePassword = keystoreProperties.getProperty("storePassword")
                    keyAlias = keystoreProperties.getProperty("keyAlias")
                    keyPassword = keystoreProperties.getProperty("keyPassword")
                }
            } else {
                // 未配置签名：回退 debug（仅本机构验证用，发布必须配置 keystore.properties）
                signingConfigs.getByName("debug")
            }
        }
    }
    kotlinOptions {
        jvmTarget = "1.8"
    }
    buildFeatures {
        buildConfig = true
    }
}

rust {
    rootDirRel = "../../../"
}

